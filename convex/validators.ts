import { v } from "convex/values";
const choice = <T extends string>(...values: T[]) =>
  v.union(...values.map((value) => v.literal(value)));
const optionalBool = v.optional(v.boolean()),
  optionalNumber = v.optional(v.number()),
  optionalString = v.optional(v.string());
export const deskSettings = v.object({
  volume: v.number(),
  muted: optionalBool,
  bell: v.boolean(),
  room: choice("study", "library", "attic"),
  light: choice("auto", "day", "lamp", "mixed", "office"),
  desk: v.optional(
    choice(
      "walnut",
      "oak",
      "leather",
      "linen",
      "slate",
      "cherry",
      "maple",
      "rosewood",
    ),
  ),
  paper: v.optional(
    v.object({
      ruling: v.optional(
        choice("blank", "narrow", "wide", "margin", "graph", "dots"),
      ),
      stock: choice(
        "bond",
        "white",
        "onionskin",
        "kraft",
        "ledger",
        "recycled",
      ),
      element: choice("mono", "italic", "book"),
      initials: v.boolean(),
      ribbon: choice("black", "blue", "sepia", "bichrome"),
    }),
  ),
  clock: optionalBool,
  clockChosen: optionalBool,
  ticking: optionalBool,
  ownerCard: optionalBool,
  face: choice("mono", "book"),
  reduceMotion: v.boolean(),
  largeType: v.boolean(),
  typeSize: v.optional(
    v.union(v.literal(1), v.literal(2), v.literal(3), v.literal(4)),
  ),
  immersive: optionalBool,
  model: optionalString,
  variations: v.optional(
    v.object({
      finish: optionalString,
      knob: optionalString,
      accent: optionalString,
    }),
  ),
  clockStyle: optionalString,
  roomLight: optionalBool,
  roomLightPreset: v.optional(choice("auto", "day", "study", "office")),
  deskLightIntensity: optionalNumber,
  deskLightSpread: optionalNumber,
  deskLightReach: optionalNumber,
  deskLightSource: v.optional(choice("overhead", "rail")),
  deskLightTone: v.optional(choice("tungsten", "amber", "halogen")),
  deskLightColor: optionalString,
  railLightIntensity: optionalNumber,
  railLightSpread: optionalNumber,
  railLightReach: optionalNumber,
  railLightTone: v.optional(choice("tungsten", "amber", "halogen")),
  railLightColor: optionalString,
  clockPosition: v.optional(v.object({ x: v.number(), y: v.number() })),
  layoutPreset: v.optional(choice("minimal", "balanced", "full", "custom")),
  visibleControls: v.optional(
    v.array(
      choice(
        "bold",
        "italic",
        "ribbon",
        "section",
        "underline",
        "typeface",
        "typeSize",
        "ruling",
        "paperCounters",
        "light",
        "volume",
        "feed",
        "save",
        "share",
        "copy",
        "focus",
        "mute",
      ),
    ),
  ),
});
